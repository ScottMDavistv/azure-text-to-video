"""Provider-free 300-second synthetic renderer for explicitly guarded worker use.

No cloud SDK or paid provider. Fixed ffmpeg arguments derived only from a
validated, server-selected scene plan; never interpolate prompt into commands.
"""
import json
import os
from pathlib import Path
import subprocess
import tempfile

from synthetic_scene_plan import validate_scene_plan

MAX_BYTES = 100 * 1024 * 1024

class SyntheticRenderError(RuntimeError):
    pass

def assert_offline():
    if os.getenv("VIDEO_RENDER_PROVIDER", "disabled").strip().lower() != "disabled":
        raise SyntheticRenderError("Synthetic rendering requires disabled paid provider")
    for name in ("ENABLE_PAID_FAL_WORKER", "ENABLE_LIVE_VIDEO_RENDERING",
                 "ENABLE_WORKER_CONSUMPTION"):
        if os.getenv(name, "false").strip().lower() in ("1", "true", "yes"):
            raise SyntheticRenderError("Paid/live worker flag prohibited for synthetic rendering")

def invoke(args, *, runner=subprocess.run, timeout=120):
    try:
        result = runner(args, capture_output=True, text=True,
                        check=False, timeout=timeout)
    except (OSError, subprocess.TimeoutExpired):
        raise SyntheticRenderError("Synthetic FFmpeg executable unavailable or timed out") from None
    if result.returncode:
        raise SyntheticRenderError("Synthetic FFmpeg rendering or inspection failed")
    return result.stdout

def render_scene_plan(plan, *, runner=subprocess.run):
    assert_offline()
    plan = validate_scene_plan(plan)
    with tempfile.TemporaryDirectory(prefix="textvideo-synthetic-") as temp:
        directory = Path(temp)
        segments = []
        for index, scene in enumerate(plan["scenes"]):
            clip = directory / ("scene-%03d.mp4" % index)
            duration = scene["duration_seconds"]
            color = scene["visual"]["color"]
            frequency = scene["audio"]["frequency_hz"]
            invoke(["ffmpeg", "-hide_banner", "-loglevel", "error", "-nostdin", "-y",
                    "-f", "lavfi", "-i", f"color=c={color}:s=320x180:r=12:d={duration}",
                    "-f", "lavfi", "-i", f"sine=frequency={frequency}:sample_rate=16000:duration={duration}",
                    "-c:v", "libx264", "-preset", "ultrafast", "-crf", "34",
                    "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "32k",
                    "-ar", "16000", "-shortest", str(clip)], runner=runner)
            segments.append(clip)
        playlist = directory / "playlist.txt"
        # Paths are generated by us, not provided by user prompts.
        playlist.write_text("".join("file '%s'\n" % str(clip) for clip in segments),
                            encoding="utf-8")
        output = directory / "video.mp4"
        invoke(["ffmpeg", "-hide_banner", "-loglevel", "error", "-nostdin", "-y",
                "-f", "concat", "-safe", "0", "-i", str(playlist),
                "-c", "copy", "-movflags", "+faststart", str(output)], runner=runner)
        try:
            size = output.stat().st_size
            if size < 1 or size > MAX_BYTES:
                raise SyntheticRenderError("Synthetic MP4 violates artifact size limit")
            probe = json.loads(invoke([
                "ffprobe", "-v", "error", "-show_entries",
                "format=duration:stream=codec_type,codec_name",
                "-of", "json", str(output),
            ], runner=runner))
            types = {item.get("codec_type") for item in probe.get("streams", [])}
            duration = float(probe["format"]["duration"])
            if not {"video", "audio"}.issubset(types) or abs(duration - 300) > 0.6:
                raise SyntheticRenderError("Synthetic MP4 audio/video duration check failed")
            return output.read_bytes()
        except (OSError, ValueError, KeyError, TypeError):
            raise SyntheticRenderError("Synthetic MP4 validation failed") from None
